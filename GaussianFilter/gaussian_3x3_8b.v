//========================================================================
// gaussian_3x3_8b.v —— 8bit 3×3 高斯滤波核（GaussianFilter 工程）
//
// 功能：输入 3×3 窗口 9 个像素，输出高斯加权平均：
//   out = (w11·1 + w12·2 + w13·1 + w21·2 + w22·4 + w23·2
//        + w31·1 + w32·2 + w33·1) >> 4
//
// 【系数怎么来的（重点推导，配 README）】
//   1. 一维高斯采样 G(x)=exp(-x²/2σ²)：
//      σ=0.849 精确版：exp(-1/(2σ²))=1/2 → σ=0.849，采样 {0.5,1,0.5}×2 = [1,2,1]
//      σ≈1 习惯版：采样 {0.607,1,0.607} 舍入近似 [1,2,1]（近似，非精确）
//   2. 可分离：二维高斯 = 一维外积 [1,2,1]ᵀ×[1,2,1] = [[1,2,1],[2,4,2],[1,2,1]]
//   3. 核总和 = 16 = 2⁴ → 归一化就是右移 4 位（纯移位，2 的幂的福利）
//
// 【为什么 0 个乘法器（对比 pre-adder）】
//   系数 1/2/4 全是 2 的幂 → 对称合并后直接移位加权：
//     角组（4 像素，系数 1）→ 求和即可，不乘
//     边组（4 像素，系数 2）→ 求和后左移 1
//     中心（1 像素，系数 4）→ 左移 2
//   教材的 pre-adder（9 乘法→4 乘法）在这里退化到 0 乘法器——
//   pre-adder 的价值在任意系数对称核（如 Sobel）才体现。
//
// 【舍入与饱和】
//   >>4 截断有 ≤15/16≈0.94 LSB 且全负偏（图像变暗），先加 8（2^(4-1)）四舍五入：
//   out = (sum + 8) >> 4，误差上界 0.5 LSB（与均值核 +256 舍入同一风格）
//   理论最大 4080，>>4 = 255 恰好满值；饱和 255 为防御保留
//
// 【位宽推导（写死）】
//   角组/边组：4×255 = 1020 < 2^10 → 10bit（级1，4 输入加法树；中心 w22 直取无加法器）
//   edge<<1 = 2040 < 2^11；w22<<2 = 1020 < 2^10（级2，移位是布线零逻辑）
//   加权和：1020 + 2040 + 1020 = 4080 < 2^12 → 12bit
//   +8 舍入：4088 < 4096 不溢出
//
// 【流水】级1 分组和 → 级2 移位加权和 → 级3 舍入+右移+饱和 = 3 级，
//   valid 链 LAT=3 严格对齐（验证标准：级数与 LAT 必须一一对应）
// 复位：全部流水寄存器异步复位（negedge rst_n 进敏感表），纯数据通路无存储
//========================================================================
`timescale 1ns/1ps

module gaussian_3x3_8b (
    input               clk,
    input               rst_n,       // 低电平复位（异步）

    // 3×3 窗口，9 个 8bit 像素（p00=左上，p22=右下，行×列）
    input  [7:0]        p00, p01, p02,
    input  [7:0]        p10, p11, p12,
    input  [7:0]        p20, p21, p22,
    input               valid_in,    // 窗口有效（接行缓存 matrix_valid）

    output reg  [7:0]   dout,        // 高斯滤波结果（与 valid_out 同拍）
    output              valid_out
);

    localparam LAT = 3;              // 流水级数（valid 链对齐）

    //========================================================================
    // 级1：对称分组求和（9 → 3）
    //   角组（系数 1）：p00+p02+p20+p22（4 输入加法树，10bit）
    //   边组（系数 2）：p01+p10+p12+p21（4 输入加法树，10bit）
    //   中心（系数 4）：p11 直取，无加法器
    //========================================================================
    reg [9:0] ang;                   // 角组和
    reg [9:0] edge_sum;              // 边组和（edge 是 iverilog 保留字，不能用）
    reg [7:0] center;                // 中心（打拍对齐）

    //========================================================================
    // 级2：移位加权和（3 → 1，12bit）
    //   注意（审查修正）：+ 优先级高于 <<，括号必须显式！
    //   edge<<1 = ×2（11bit），center<<2 = ×4（10bit），纯布线
    //========================================================================
    reg [11:0] sum;

    //========================================================================
    // 级3：舍入 + 右移 + 饱和（组合逻辑 + 寄存器输出）
    //========================================================================
    reg [LAT-1:0] valid_chain;

    // 级1：分组和
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ang       <= 10'd0;
            edge_sum  <= 10'd0;
            center    <= 8'd0;
        end else begin
            ang       <= {2'b00, p00} + {2'b00, p02} + {2'b00, p20} + {2'b00, p22};   // 4 角
            edge_sum  <= {2'b00, p01} + {2'b00, p10} + {2'b00, p12} + {2'b00, p21};   // 4 边
            center    <= p11;                                                           // 中心直取
        end
    end

    // 级2：加权和（括号不能省）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            sum <= 12'd0;
        else
            sum <= ang + ({1'b0, edge_sum} << 1) + ({3'b000, center} << 2);
    end

    // 级3：加 8 四舍五入、右移 4、饱和
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            dout <= 8'd0;
        else begin
            // (sum+8)>>4：4080>>4=255 恰好满值，饱和为防御保留
// 组	                像素	        组和	        加权
// 角组（系数 1）	4 个角各 255	4×255 = 1020	×1 = 1020
// 边组（系数 2）	4 个边各 255	4×255 = 1020	×2 = 2040
// 中心（系数 4）	w22 = 255	255	×4 = 1020

            if (sum + 12'd8 > 12'd4080)
                dout <= 8'd255;
            else
                dout <= (sum + 12'd8) >> 4;
        end
    end

    // valid 链：LAT=3，与数据通路逐级对齐
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            valid_chain <= {LAT{1'b0}};
        else
            valid_chain <= {valid_chain[LAT-2:0], valid_in};
    end

    assign valid_out = valid_chain[LAT-1];

endmodule