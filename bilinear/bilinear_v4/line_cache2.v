//========================================================================
// line_cache2.v —— 3 行行缓存（bilinear_v4 版，BRAM 版）
//
// 功能：一边收输入像素（一行一行地收），一边按"源坐标 (sy,sx)"把
//       双线性插值要用的 4 个邻居像素读出来。只存 3 行，不存整张图。
//       本版本用推断式 BRAM（ram_style="block"），行宽大也不会爆 LUT。
//
// 【为什么是 3 行】
//   插值一次要用 2 行：第 sy 行和第 sy+1 行。
//   同时，输入侧还在往缓存里填当前的第 w 行。
//   写 1 行 + 读 2 行 = 3 行，正好。
//
// 【"环形"是什么意思（重要）】
//   缓存只有 3 组格子，每组格子存一整行：
//     第 0 行 → 格子 0，第 1 行 → 格子 1，第 2 行 → 格子 2，
//     第 3 行 → 又放回格子 0（此时格子 0 里的第 0 行早就读完了，可以覆盖）……
//   第 r 行放哪组格子 = "r 除以 3 的余数"（代码 line[r % 3]），3 组循环用，叫"环形"。
//
// 【为什么每行要 2 块 BRAM（共 6 块）】
//   一块 BRAM 只有 1 个写口 + 1 个读口。读侧一次要读 2 列（sx 和 sx+1），
//   1 个读口不够 → 每行放 2 块内容完全相同的 BRAM：
//     一块专门读 sx 列（line_a），一块专门读 sx+1 列（line_b）。
//   写侧收像素时同时往两块里写（内容一样），读侧两块各读各的列。
//
// 【BRAM 读是"同步读"：地址 T 拍给，数据 T+1 拍才出】
//   所以 4 邻居比坐标/权重晚 1 拍，顶层要补 1 拍对齐寄存（见 bilinear_lb_top.v）。
//
// 【写侧和读侧怎么协调（反压）】
//   写侧（输入）：按顺序收像素，收满一整行就换下一组格子。
//     写之前要检查：我要覆盖的格子里，旧的那行（3 行前写的 w-3 行）
//     读侧还用不用？还用 → 不能写，把 wr_ready 拉低，让输入等一等。
//   读侧（输出）：coord_gen 给出源坐标，要读第 sy 行和第 sy+1 行。
//     这两行还没写完 → 把 rd_ready 拉低，让坐标暂停，等写侧写完。
//   一句话：写侧不覆盖读侧还在用的行，读侧不等还没写完的行。
//   放大时写得快读得慢（写侧等读侧），缩小时写得慢读得快（读侧等写侧），
//   谁落后谁等谁，不会卡死。
//
// 【帧末排空】
//   输入像素喂完、但输出还没算完时，读侧会停住（sy 不再变）。
//   此时写侧还能把最后几行写完——因为那些格子里的旧行早就被读侧用完了。
//========================================================================
`timescale 1ns/1ps

module line_cache2 #(
    parameter DW         = 24,     // 像素位宽（RGB888）
    parameter IN_WIDTH   = 112,    // 行宽（每行多少个像素）
    parameter IN_HEIGHT  = 103     // 行数（总共多少行）
)(
    input                       clk,
    input                       rst_n,       // 低电平复位（异步）

    // 写口（输入侧）：光栅顺序，一行一行来
    input  [DW-1:0]             din,
    input                       din_valid,   // 这一拍 din 有效
    output                      wr_ready,    // 写侧就绪：拉低 = 输入请暂停

    // 读口（输出侧）：源坐标来自 coord_gen
    input  [RW-1:0]             rd_sy,       // 源 y（可能越界，内部会钳位）
    input  [CW-1:0]             rd_sx,       // 源 x
    output                      rd_ready,    // 行就绪：拉低 = 坐标请暂停

    // 4 个邻居像素（同步读出，比 rd_sy/rd_sx 晚 1 拍）
    output [DW-1:0]             dout00,      // 左上  P(sy,   sx)
    output [DW-1:0]             dout10,      // 右上  P(sy,   sx+1)
    output [DW-1:0]             dout01,      // 左下  P(sy+1, sx)
    output [DW-1:0]             dout11       // 右下  P(sy+1, sx+1)
);

    // 位宽：够装下对应的数就行（+1 是给"越界到 IN"的边界值留余量）
    localparam CW = $clog2(IN_WIDTH)  + 1;   // 源 x 位宽
    localparam RW = $clog2(IN_HEIGHT) + 1;   // 源 y 位宽
    localparam WW = $clog2(IN_WIDTH);        // 写列计数位宽（0..IN_W-1）
    localparam WROW = $clog2(IN_HEIGHT) + 1; // 写行计数位宽（w 最大 IN_H）

    //========================================================================
    // 存储：3 组格子 × 每行 2 块 BRAM（内容相同，双读口）
    //   line_a = 读 sx 列用的，line_b = 读 sx+1 列用的
    //   line[格子号][列号]，格子号 0/1/2
    //   ram_style="block" 让综合器推断成真正的 BRAM（而不是 LUT）
    //========================================================================
    (* ram_style = "block" *) reg [DW-1:0] line_a [0:2] [0:IN_WIDTH-1];
    (* ram_style = "block" *) reg [DW-1:0] line_b [0:2] [0:IN_WIDTH-1];

    //========================================================================
    // 写侧状态
    //   w      = 正在写第几行（0 起；0..w-1 行已经写完）
    //   wr_col = 正在写这一行的第几列（0..IN_W-1），写满一整行就换下一行
    //========================================================================
    reg [WROW-1:0] w;
    reg [WW-1:0]   wr_col;

    // 读侧当前要用的两行（源坐标可能越界，先钳到最后一行的范围内）
    //   sy00 = 第 sy 行，sy01 = 第 sy+1 行
    wire [RW-1:0] sy00 = (rd_sy      > IN_HEIGHT-1) ? IN_HEIGHT-1 : rd_sy;
    wire [RW-1:0] sy01 = (rd_sy + 1'b1 > IN_HEIGHT-1) ? IN_HEIGHT-1 : rd_sy + 1'b1;

    // 写侧能不能写：
    //   我要写的格子是 (w % 3)，里面现在放着 3 行前写的旧行 (w-3)。
    //   只有当读侧已经用完旧行（读侧最低用到 sy00，且 sy00 已经越过 w-3）时，
    //   才能放心覆盖。前 3 行（w<3）格子从来没写过，随便写。
    //   帧末读侧停住也不怕：那时候要覆盖的旧行早就用完了。
    // 具体例子：
    //   读侧正在用第 5、6 行 → sy00 = 5
    //   写侧想写第 10 行 → 格子 10%3 = 1，里面躺着旧行 10-3 = 7
    //   检查：sy00=5 > 7 ? 否 → 旧行 7 还没被读到（读侧马上还要用 7）→ 不能写
    //   等读侧推进到窗口 {8, 9}（sy00 = 8）时：8 > 7 是 → 旧行 7 已消费完 → 可以写
    assign wr_ready = ((w < 3) || (sy00 > w - 3)) && (w < IN_HEIGHT);

    // 读侧能不能读：要用的第 sy+1 行已经写完（写侧 w 已经越过它）
    assign rd_ready = (sy01 < w);

    // 写入：din_valid 且写侧就绪时，把像素同时写进两块 BRAM（内容一样）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            w      <= {WROW{1'b0}};
            wr_col <= {WW{1'b0}};
        end
        else if (din_valid && wr_ready) begin
            line_a[w % 3][wr_col] <= din;
            line_b[w % 3][wr_col] <= din;
            if (wr_col == IN_WIDTH - 1) begin
                // 这一行写满了：换下一行，列回到 0
                wr_col <= {WW{1'b0}};
                w      <= w + 1'b1;
            end
            else begin
                wr_col <= wr_col + 1'b1;
            end
        end
    end

    //========================================================================
    // 读侧：按源坐标把 4 个邻居读出来（BRAM 同步读，地址 T 拍给、数据 T+1 拍出）
    //   sy 行的格子是 (sy00 % 3)，sy+1 行的格子是 (sy01 % 3)
    //   line_a 读 sx 列（左上、左下），line_b 读 sx+1 列（右上、右下）
    //   列也可能越界（sx+1 到行尾），先钳位
    //   读输出寄存器用同步复位（if(!rst_n) 在 posedge clk 内、不进敏感表），
    //   保证 BRAM 推断成功（守 BRAM 铁律）
    //========================================================================
    wire [CW-1:0] sx00 = (rd_sx      > IN_WIDTH-1)  ? IN_WIDTH-1  : rd_sx;
    wire [CW-1:0] sx10 = (rd_sx + 1'b1 > IN_WIDTH-1)? IN_WIDTH-1  : rd_sx + 1'b1;

    reg [DW-1:0] rd00, rd10, rd01, rd11;
    always @(posedge clk) begin
        if (!rst_n) begin
            rd00 <= {DW{1'b0}};
            rd10 <= {DW{1'b0}};
            rd01 <= {DW{1'b0}};
            rd11 <= {DW{1'b0}};
        end
        else begin
            rd00 <= line_a[sy00 % 3][sx00];   // 左上：sy 行的 sx 列
            rd10 <= line_b[sy00 % 3][sx10];   // 右上：sy 行的 sx+1 列
            rd01 <= line_a[sy01 % 3][sx00];   // 左下：sy+1 行的 sx 列
            rd11 <= line_b[sy01 % 3][sx10];   // 右下：sy+1 行的 sx+1 列
        end
    end

    assign dout00 = rd00;
    assign dout10 = rd10;
    assign dout01 = rd01;
    assign dout11 = rd11;

endmodule