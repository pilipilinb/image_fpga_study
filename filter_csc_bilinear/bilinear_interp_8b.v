//========================================================================
// bilinear_interp_8b.v —— 8bit 单通道双线性插值核（bilinear_v3 版）
// 功能：对 2×2 邻域 4 像素做双线性插值，输出 8bit 像素
//   out = p00·(1-u)(1-v) + p01·u(1-v) + p10·(1-u)v + p11·u·v
//   p00 = 左上 P(sy,  sx)　　权重 w00 = (1-u)(1-v)
//   p01 = 右上 P(sy,  sx+1)　权重 w01 = u(1-v)
//   p10 = 左下 P(sy+1,sx)　　权重 w10 = (1-u)v
//   p11 = 右下 P(sy+1,sx+1)　权重 w11 = u·v
//   u = x 方向权重、v = y 方向权重，FRAC_BITS 位定点（0~1 对应 0~2^FB-1）
//
// 来源：清洗 bilinear_v2/case1_calculate.v，修正三处：
//   1. valid 链：case1 用 6 位寄存器取 [5]（延迟 7 拍 vs 数据 9 级，早 2 拍），
//      本版用 LAT=8 移位寄存器与 8 级关键路径严格对齐
//   2. 像素对齐：原 S5 只补 1 级（像素 2 级 vs 权重 4 级，m00 汇合错位 2 拍），
//      本版像素补 3 级对齐权重路径
//   3. 饱和/舍入：case1 的 if(post_cal_data>255) 检查 8 位旧值永假（死代码），
//      且舍入 +1 在 8 位寄存器会回绕（255+1=0）；本版用 9 位中间量防回绕
//   4. 冗余副本：删除 case1 的 _reg_copy 副本寄存器（同一 reg 多扇出合法）
//
// 位宽链（一般式，FRAC_BITS 默认冻结 8）：
//   u/v          FB      位（8）
//   1-u/1-v      FB+1    位（9；u=0 时 1-u=2^FB 需进位位，用 {1'b0,~u}+1 实现）
//   权重 w       2(FB+1) 位（18）= (1-u)(1-v) 等，9×9 乘积
//   权重×像素    2FB+10  位（26）= 18×8
//   两项和       2FB+10  位（26；实际值 < 2^(2FB+8)，权重和约束保证，无需进位位）
//   四项和       2FB+11  位（27；实际值 < 2^(2FB+8)，1 位进位保护）
//   右移 2FB 位、舍入位取 [2FB-1]、9 位中间量舍入后饱和 255
//
// 流水线：关键路径 8 级（输入寄存→1-u/v→权重输入寄存→权重乘法→
//   权重×像素→乘积寄存→两项和→四项和→输出），像素对齐 3 级旁路
//   补齐与权重级差（S5a/S5b/S5c），与 LAT=8 严格对齐
// 复位：全部流水寄存器异步复位（negedge rst_n 进敏感表），无 BRAM
// 帧边界：本核为纯数据通路，无帧概念；帧末防御由上游 coord_gen 的
//   frame_active 门控 valid_in 完成，valid 链把 0 逐级传递即可
//========================================================================
`timescale 1ns/1ps

module bilinear_interp_8b #(
    parameter FRAC_BITS = 8        // 定点小数位（与 coord_gen 绑定，冻结 8）
)(
    input                       clk,
    input                       rst_n,       // 低电平复位（异步）
    input  [FRAC_BITS-1:0]      u_frac,      // x 方向权重（0~1 对应 0~2^FB-1）
    input  [FRAC_BITS-1:0]      v_frac,      // y 方向权重
    input  [7:0]                p00,         // 左上 P(sy, sx)
    input  [7:0]                p01,         // 右上 P(sy, sx+1)
    input  [7:0]                p10,         // 左下 P(sy+1, sx)
    input  [7:0]                p11,         // 右下 P(sy+1, sx+1)
    input                       valid_in,    // 输入有效（接上游 valid_out）
    output reg  [7:0]           pix_out,     // 插值结果（与 valid_out 同拍）
    output                      valid_out    // 输出有效
);

    //========================================================================
    // 位宽派生
    //========================================================================
    localparam FB  = FRAC_BITS;
    localparam LAT = 8;              // 关键路径寄存器级数（valid 链对齐）
    localparam WF  = FB + 1;         // 1-u / 1-v 位宽
    localparam WW  = 2 * (FB + 1);   // 权重位宽（(FB+1)×(FB+1)）
    localparam PW  = WW + 8;         // 权重×像素位宽
    localparam SW  = PW + 1;         // 四项和位宽（1 位进位保护）

    //========================================================================
    // Stage1：输入寄存
    //========================================================================
    reg [FB-1:0] u_r, v_r;
    reg [7:0]    p00_r, p01_r, p10_r, p11_r;

    //========================================================================
    // Stage2：存储 权重
    //   {1'b0, ~u} + 1 = 2^FB - u = 1-u，u=0 时结果 2^FB 需 FB+1 位
    //========================================================================
    reg [WF-1:0] u_1, v_1; //存储 1-u/1-v
    reg [WF-1:0] u_w, v_w; //存储 u/v

    //========================================================================
    // Stage3：权重乘法输入寄存（同一 reg 多扇出驱动 4 个乘法器，无需副本）
    //========================================================================
    reg [WF-1:0] u_1_r, v_1_r, u_w_r, v_w_r;

    //========================================================================
    // Stage4：4 个权重乘法（(FB+1)×(FB+1) = WW 位）
    //========================================================================
    reg [WW-1:0] w00_r, w01_r, w10_r, w11_r;

    //========================================================================
    // Stage5：像素对齐寄存（3 级：S5a/S5b/S5c，补齐与权重 S2/S3/S4 的级差）
    //   权重路径 S1→S2→S3→S4 共 4 级（3 拍）；像素只有 S1，需再补 3 级
    //   使 m00 汇合时像素与权重同拍（原版只补 1 级，错位 2 拍）
    //========================================================================
    reg [7:0] p00_r2, p01_r2, p10_r2, p11_r2;
    reg [7:0] p00_r3, p01_r3, p10_r3, p11_r3;
    reg [7:0] p00_r4, p01_r4, p10_r4, p11_r4;

    //========================================================================
    // Stage6：权重×像素（组合，WW×8 = PW 位）
    //========================================================================
    wire [PW-1:0] m00, m01, m10, m11;

    //========================================================================
    // Stage7a：乘积寄存
    //========================================================================
    reg [PW-1:0] m00_r, m01_r, m10_r, m11_r;

    //========================================================================
    // Stage7b：两项和（PW 位；实际值 < 2^(2FB+8)/2，无需进位位）
    //========================================================================
    reg [PW-1:0] s0_r, s1_r;

    //========================================================================
    // Stage7c：四项和（SW 位，1 位进位保护）
    //========================================================================
    reg [SW-1:0] sum_r;

    //========================================================================
    // valid 链：LAT 位移位寄存器，与数据通路逐级对齐
    //========================================================================
    reg [LAT-1:0] valid_chain;

    //----------------------------------------------------------------------------
    // Stage1：输入寄存
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            u_r   <= {FB{1'b0}};
            v_r   <= {FB{1'b0}};
            p00_r <= 8'd0;
            p01_r <= 8'd0;
            p10_r <= 8'd0;
            p11_r <= 8'd0;
        end else begin
            u_r   <= u_frac;
            v_r   <= v_frac;
            p00_r <= p00;
            p01_r <= p01;
            p10_r <= p10;
            p11_r <= p11;
        end
    end

    //----------------------------------------------------------------------------
    // Stage2：1-u / 1-v
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            u_1 <= {WF{1'b0}};
            v_1 <= {WF{1'b0}};
            u_w <= {WF{1'b0}};
            v_w <= {WF{1'b0}};
        end else begin
            u_1 <= {1'b0, ~u_r} + 1'b1;   // 2^FB - u_r
            v_1 <= {1'b0, ~v_r} + 1'b1;   // 2^FB - v_r
            u_w <= {1'b0, u_r};
            v_w <= {1'b0, v_r};
        end
    end

    /**
    ----------------------------------------------------------------------------
    // Stage3：权重乘法输入寄存
    此处是为了优化时序，所以寄存了一次。如果不加寄存就会导致
    Stage2 的取反加一（~u + 1）和 Stage4 的 9×9 乘法直接串在一起 
    //----------------------------------------------------------------------------
    */
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            u_1_r <= {WF{1'b0}};
            v_1_r <= {WF{1'b0}};
            u_w_r <= {WF{1'b0}};
            v_w_r <= {WF{1'b0}};
        end else begin
            u_1_r <= u_1;
            v_1_r <= v_1;
            u_w_r <= u_w;
            v_w_r <= v_w;
        end
    end

    //----------------------------------------------------------------------------
    // Stage4：权重乘法
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            w00_r <= {WW{1'b0}};
            w01_r <= {WW{1'b0}};
            w10_r <= {WW{1'b0}};
            w11_r <= {WW{1'b0}};
        end else begin
            w00_r <= u_1_r * v_1_r;   // (1-u)(1-v)
            w01_r <= u_w_r * v_1_r;   // u(1-v)
            w10_r <= u_1_r * v_w_r;   // (1-u)v
            w11_r <= u_w_r * v_w_r;   // u·v
        end
    end

    //----------------------------------------------------------------------------
    // Stage5a/5b/5c：像素对齐寄存（3 级）
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p00_r2 <= 8'd0;
            p01_r2 <= 8'd0;
            p10_r2 <= 8'd0;
            p11_r2 <= 8'd0;
        end else begin
            p00_r2 <= p00_r;
            p01_r2 <= p01_r;
            p10_r2 <= p10_r;
            p11_r2 <= p11_r;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p00_r3 <= 8'd0;
            p01_r3 <= 8'd0;
            p10_r3 <= 8'd0;
            p11_r3 <= 8'd0;
        end else begin
            p00_r3 <= p00_r2;
            p01_r3 <= p01_r2;
            p10_r3 <= p10_r2;
            p11_r3 <= p11_r2;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            p00_r4 <= 8'd0;
            p01_r4 <= 8'd0;
            p10_r4 <= 8'd0;
            p11_r4 <= 8'd0;
        end else begin
            p00_r4 <= p00_r3;
            p01_r4 <= p01_r3;
            p10_r4 <= p10_r3;
            p11_r4 <= p11_r3;
        end
    end

    //----------------------------------------------------------------------------
    // Stage6：权重×像素（组合）
    //----------------------------------------------------------------------------
    assign m00 = w00_r * p00_r4;   // (1-u)(1-v)·p00
    assign m01 = w01_r * p01_r4;   // u(1-v)·p01
    assign m10 = w10_r * p10_r4;   // (1-u)v·p10
    assign m11 = w11_r * p11_r4;   // u·v·p11

    //----------------------------------------------------------------------------
    // Stage7a：乘积寄存
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            m00_r <= {PW{1'b0}};
            m01_r <= {PW{1'b0}};
            m10_r <= {PW{1'b0}};
            m11_r <= {PW{1'b0}};
        end else begin
            m00_r <= m00;
            m01_r <= m01;
            m10_r <= m10;
            m11_r <= m11;
        end
    end

    //----------------------------------------------------------------------------
    // Stage7b：两项和（上行两项 / 下行两项）
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            s0_r <= {PW{1'b0}};
            s1_r <= {PW{1'b0}};
        end else begin
            s0_r <= m00_r + m01_r;   // (1-v) 方向两项
            s1_r <= m10_r + m11_r;   // v 方向两项
        end
    end

    //----------------------------------------------------------------------------
    // Stage7c：四项和（1 位进位保护）
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            sum_r <= {SW{1'b0}};
        else
            sum_r <= {1'b0, s0_r} + {1'b0, s1_r};
    end

    //----------------------------------------------------------------------------
    // Stage8：右移 2FB 位 + 四舍五入 + 饱和，输出寄存
    //   结果 = sum_r 右移 2FB 位取 [2FB+7:2FB]，舍入位 = sum_r[2FB-1]
    // 因为u、v的小数位都是FB位，v*u小数位是2FB，所以右移2FB位，然后加2fb-1位，进行四舍五入操作
    //========================================================================
    wire [8:0] rounded = {1'b0, sum_r[2*FB+7 : 2*FB]} + {8'd0, sum_r[2*FB-1]};
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            pix_out <= 8'd0;
        else
            pix_out <= (rounded > 9'd255) ? 9'd255 : rounded[7:0];
    end

    //----------------------------------------------------------------------------
    // valid 链：与数据通路同拍（LAT=9）
    //----------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            valid_chain <= {LAT{1'b0}};
        else
            valid_chain <= {valid_chain[LAT-2:0], valid_in};
    end

    assign valid_out = valid_chain[LAT-1];

endmodule