//========================================================================
// sobel_3x3_8b.v —— 8bit 3×3 Sobel 边缘检测核（sobel 工程，W4 差分卷积）
//
// 功能：输入 3×3 窗口 9 个像素（p00=左上 … p22=右下，w22 为中心），输出：
//   o_mag  = 梯度幅值（8bit，AMBM 估算后右移 2 位 + 饱和）
//   o_edge = 阈值二值化边缘图（0/255，阈值 thresh 可配）
//
// 【Sobel 算子（差分卷积）】
//   Gx = (p02 + 2·p12 + p22) − (p00 + 2·p10 + p20)   ← 左右列加权差：垂直边缘
//   Gy = (p20 + 2·p21 + p22) − (p00 + 2·p01 + p02)   ← 上下行加权差：水平边缘
//   与均值/高斯（平滑卷积）对比：Sobel 核系数和为 0，平坦区输出 0，
//   只有灰度突变处非 0——"边缘 = 灰度变化率"。
//
// 【零乘法器实现（系数 0/±1/±2）】
//   核系数全部是 0/±1/±2：×2 用左移 1 位（p<<1），×0 直接不接，
//   ×1 直接连线——全程只有加减法和移位，0 乘法器 0 DSP。
//   例：Gx 正项和 sumR = p02 + (p12<<1) + p22，负项和 sumL = p00 + (p10<<1) + p20
//
// 【幅值估算：Alpha-Max-Beta-Min（α=1，β=0.5）】
//   精确幅值 = sqrt(Gx²+Gy²)，FPGA 上开方代价高；AMBM 用线性近似：
//     mag = max(|Gx|,|Gy|) + (min(|Gx|,|Gy|) >> 1)     ← β=0.5 即右移 1 位
//   误差分析：令 r = min/max，误差率 = (1+0.5r)/sqrt(1+r²) − 1，
//   纯水平/垂直边（r=0）误差 0，45° 对角（r=1）约 +6.07%，最差约 +6.5%
//   （只偏大不偏小，阈值粗筛可接受——详情见 README）
//
// 【位宽推导（逐级）】
//   单侧和  p02 + 2p12 + p22     最大 2·255+255 = 1020 → [10:0]（11bit 无符号）
//   Gx/Gy   正负和之差            范围 ±1020            → signed [10:0]（11bit）
//   |Gx|    取绝对值              最大 1020            → [10:0]（11bit 无符号）
//   mag     max + (min>>1)        最大 1020+510=1530    → [11:0]（12bit）
//   o_mag   mag>>2 后饱和          382 超 255 钳掉      → [7:0]
//   注意：11bit signed 的 -1024 取绝对值会溢出，但 Gx/Gy 实际范围
//   ±1020 不会触发（-1024 需要 255-0-255 全极值才可能，数学上不可达）
//
// 【流水】3 组寄存器（LAT=3）：组1 寄存 Gx/Gy → 组2 寄存 mag → 组3 寄存输出
//   组合逻辑（差分/AMBM/饱和阈值）夹在寄存器之间——"拍" = 寄存器组数，
//   组合块不占拍（同一拍内算完，拍沿寄存）。
//   valid 链 LAT=3 与 3 组寄存器一一对应（工程铁律：寄存器组数-LAT 对齐）
// 复位：组合网络纯数据通路，仅流水寄存器异步复位。
//========================================================================
`timescale 1ns/1ps

module sobel_3x3_8b (
    input               clk,
    input               rst_n,       // 低电平复位（异步）

    // 3×3 窗口，9 个 8bit 像素（p00=左上，p22=右下，行×列）
    input  [7:0]        p00, p01, p02,
    input  [7:0]        p10, p11, p12,
    input  [7:0]        p20, p21, p22,
    input               valid_in,    // 窗口有效（接行缓存 matrix_valid）

    input  [7:0]        thresh,      // 二值化阈值（可配，慢信号不打拍）

    output reg  [7:0]   o_mag,       // 梯度幅值（AMBM，>>2 + 饱和，与 valid_out 同拍）
    output reg  [7:0]   o_edge,      // 边缘二值图：0 或 255
    output              valid_out
);

    localparam LAT = 3;              // 寄存器组数 = 3（valid 链对齐）

    //========================================================================
    // 组合块1（第 1 组寄存器之前）：Gx/Gy 两路差分 —— 零乘法器（×2 = 左移 1 位）
    //   正项和/负项和各自用 2 层加法树（8bit 相加 → 11bit 和）
    //========================================================================
    wire [10:0] gx_sumR = {3'b0, p02} + {2'b0, p12, 1'b0} + {3'b0, p22};  // p02 + 2p12 + p22
    wire [10:0] gx_sumL = {3'b0, p00} + {2'b0, p10, 1'b0} + {3'b0, p20};  // p00 + 2p10 + p20
    wire [10:0] gy_sumB = {3'b0, p20} + {2'b0, p21, 1'b0} + {3'b0, p22};  // p20 + 2p21 + p22
    wire [10:0] gy_sumT = {3'b0, p00} + {2'b0, p01, 1'b0} + {3'b0, p02};  // p00 + 2p01 + p02

    wire signed [10:0] gx = $signed(gx_sumR) - $signed(gx_sumL);  // ±1020
    wire signed [10:0] gy = $signed(gy_sumB) - $signed(gy_sumT);  // ±1020

    // 第 1 组寄存器 gx_r/gy_r（第 1 拍）
    reg signed [10:0] gx_r, gy_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            gx_r <= 11'sd0;
            gy_r <= 11'sd0;
        end else begin
            gx_r <= gx;
            gy_r <= gy;
        end
    end

    //========================================================================
    // 组合块2（第 2 组寄存器之前）：绝对值 + AMBM 幅值估算
    //   ax/ay：符号位取反+1 得绝对值（范围 0..1020，11bit 放得下）
    //   M/m：一个比较器同时分出 max 和 min（max 和 min 共用一次比较）
    //   mag = M + (m >> 1)：β=0.5 即右移 1 位；M 11bit + m>>1 ≤ 1020+510 →
    //   12bit 才放得下，加法器两侧显式扩到 12bit
    //========================================================================
    wire [10:0] ax = gx_r[10] ? (~gx_r + 11'd1) : gx_r[10:0];
    wire [10:0] ay = gy_r[10] ? (~gy_r + 11'd1) : gy_r[10:0];

    wire        mx_ge = (ax >= ay);           // 1 个比较器分两路
    wire [10:0] Mm    = mx_ge ? ax : ay;      // max
    wire [10:0] mm    = mx_ge ? ay : ax;      // min

    wire [11:0] mag   = {1'b0, Mm} + {2'b0, mm[10:1]};  // 12bit：max + (min>>1)

    // 第 2 组寄存器 mag_r（第 2 拍）
    reg [11:0] mag_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            mag_r <= 12'd0;
        else
            mag_r <= mag;
    end

    //========================================================================
    // 组合块3（第 3 组寄存器之前）：右移 2 位归一化 + 饱和 + 阈值二值化
    //   注意：下面 always @(*) 是纯组合逻辑，不占拍——o_mag_tmp/o_edge_tmp
    //   只是"第 3 拍边沿要寄存的值"，真正上寄存器的是后面的 o_mag/o_edge
    //   先 >>2 再饱和（而不是先饱和再移位）：强边缘 1530/4=382 饱和到 255，
    //   一般边缘（如 100 级差 → 400/4=100）保留灰度区分度
    //========================================================================
    wire [8:0] m8 = mag_r[11:2];                       // mag>>2，0..382（9bit）

    reg [7:0]  o_mag_tmp;
    reg [7:0]  o_edge_tmp;
    always @(*) begin
        if (m8 > 9'd255)       o_mag_tmp = 8'd255;      // 饱和：382 钳到 255
        else                   o_mag_tmp = m8[7:0];
        if (m8 > {1'b0, thresh}) o_edge_tmp = 8'd255;   // 阈值比较（9bit vs 8bit 零扩展）
        else                     o_edge_tmp = 8'd0;
    end

    //========================================================================
    // 第 3 组寄存器 o_mag/o_edge + valid 链（LAT=3 = 3 组寄存器：gx_r → mag_r → o_mag）
    //   valid 链 3bit 逐级移位，chain[2] 与输出同拍（第 3 组寄存器出口）
    //========================================================================
    reg [LAT-1:0] valid_chain;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            o_mag  <= 8'd0;
            o_edge <= 8'd0;
            valid_chain <= {LAT{1'b0}};
        end else begin
            o_mag  <= o_mag_tmp;
            o_edge <= o_edge_tmp;
            valid_chain <= {valid_chain[LAT-2:0], valid_in};
        end
    end

    assign valid_out = valid_chain[LAT-1];

endmodule