//========================================================================
// mean_3x3_8b.v —— 8bit 3×3 均值滤波核（MeanFilter 工程）
//
// 功能：输入 3×3 窗口的 9 个像素，输出它们的平均值。
//       均值 = 9 个像素求和 ÷ 9，系数全是 1/9，所以没有乘法——
//       只有"9 路加法树" + 最后一步"除以 9"。
//
// 【除以 9 怎么做（核心知识点）】
//   9 不是 2 的幂，不能直接右移。两种做法：
//     a) 直接写 sum/9（综合器展开成大除法器，费资源）
//     b) 定点近似：1/9 ≈ 57/512  （57/512 = 0.111328，真值 0.111111，误差 0.2%）
//        out = (sum×57 + 256) >> 9
//        +256 是四舍五入（右移 9 位前加 2^8），最后饱和到 255。
//   本核用 (b)——纯乘加，可进 DSP48，误差 < 0.5 LSB（8bit 视觉无感），
//   这就是"非 2 幂除数"的定点化处理，面试常问。
//
// 【位宽推导】
//   行和：3×255 = 765 < 2^10 → 10bit
//   sum： 9×255 = 2295 < 2^12 → 12bit
//   ×57： 2295×57 = 130815 < 2^17 → 18bit 中间量
//   +256 → 18bit；>>9 → 9bit；饱和钳到 255
//
// 【流水】3 级：① 每行 3 像素求和（3 个加法器）→ ② 3 行和相加
//       → ③ 乘 57 + 舍入 + 右移 + 饱和；valid 链 LAT=3
// 复位：全部流水寄存器异步复位（negedge rst_n 进敏感表），纯数据通路无存储
//========================================================================
`timescale 1ns/1ps

module mean_3x3_8b (
    input               clk,
    input               rst_n,       // 低电平复位（异步）

    // 3×3 窗口，9 个 8bit 像素（p00=左上，p22=右下，行×列）
    input  [7:0]        p00, p01, p02,   // 第 0 行（最老行）
    input  [7:0]        p10, p11, p12,   // 第 1 行
    input  [7:0]        p20, p21, p22,   // 第 2 行（当前行）
    input               valid_in,        // 窗口有效（接行缓存 matrix_valid）

    output reg  [7:0]   dout,            // 均值结果（与 valid_out 同拍）
    output              valid_out
);

    localparam LAT = 3;              // 流水级数（valid 链对齐）

    //========================================================================
    // 级1：每行 3 像素求和（9 → 3，结果 10bit）
    //========================================================================
    reg [9:0] r0, r1, r2;

    //========================================================================
    // 级2：3 行和相加（3 → 1，结果 12bit）
    //========================================================================
    reg [11:0] sum;

    // 级1：每行 3 像素求和（9 → 3，结果 10bit）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            r0 <= 10'd0;
            r1 <= 10'd0;
            r2 <= 10'd0;
        end else begin
            r0 <= {2'b00, p00} + {2'b00, p01} + {2'b00, p02};   // 第 0 行 3 像素
            r1 <= {2'b00, p10} + {2'b00, p11} + {2'b00, p12};   // 第 1 行 3 像素
            r2 <= {2'b00, p20} + {2'b00, p21} + {2'b00, p22};   // 第 2 行 3 像素
        end
    end

    // 级2：行和相加（3 行和 → 1 个总和，结果 12bit）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            sum <= 12'd0;
        else
            sum <= {1'b0, r0} + {1'b0, r1} + {1'b0, r2};   // 10bit×3 相加 → 需 12bit
    end

    //========================================================================
    // 级3：除 9 定点近似 (sum×57 + 256) >> 9，饱和
    //   乘、舍入、右移、饱和合并在一级完成（组合乘法 + 寄存器输出），
    //   保证数据通路共 3 级寄存器，与 valid 链 LAT=3 严格对齐
    //========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            dout <= 8'd0;
        else begin
            // sum×57：12bit×7bit → 18bit 内；+256 四舍五入；>>9 → 9bit
            // 理论最大 225x9×57+256 = 131071，>>9 = 255.998，饱和防御
            if (sum * 18'd57 + 18'd256 > 18'd130815)
                dout <= 8'd255;
            else
                dout <= (sum * 18'd57 + 18'd256) >> 9;
        end
    end

    // valid 链：LAT=3
    reg [LAT-1:0] valid_chain;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            valid_chain <= {LAT{1'b0}};
        else
            valid_chain <= {valid_chain[LAT-2:0], valid_in};
    end

    assign valid_out = valid_chain[LAT-1];

endmodule