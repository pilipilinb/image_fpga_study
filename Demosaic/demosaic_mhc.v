//========================================================================
// demosaic_mhc.v —— MHC 版去马赛克核（Demosaic 工程，W3）
//
// 和双线性版的区别（一句话）：双线性只是"邻居求平均"，画面会发糊；
//   MHC 在平均的基础上加了一项"细节校正"——用中心像素和更远的同色像素之差，
//   把图像的锐度还回来（类似"均值 + 高通"）。
//
// 【公式（照伪代码.txt 的 MHC 版，W[行][列] 是 5×5 窗口，W[2][2] 是中心）】
//   中心是 R（B 相位把 R/B 对调）：
//     R = W22                                  直通
//     G = ( 4·W22 + 2·十字4个G − 远端十字4个 ) >> 3
//     B = ( 4·W22 + 2·对角4个B − 远端十字4个 ) >> 3
//       注：远端十字 = W[0][2], W[4][2], W[2][0], W[2][4]（离中心 2 格的那 4 个，
//           在 RGGB 里它们也是 R，所以"W22 − 远端"就是中心的细节量）
//   中心是 Gr（Gb 把 R/B 对调）：
//     G = W22                                  直通
//     R = ( 2·W22 + 2·左右2个R − 左右远端2个 ) >> 2
//     B = ( 2·W22 + 2·上下2个B − 上下远端2个 ) >> 2
//
// 【为什么会出现负数和超 255】
//   减号那项在平坦区可能比加号大 → 结果可能为负（画面暗处会出现）；
//   加号那项在强边缘可能很大 → 如 3060>>3 = 382 > 255。
//   所以实现上：正项、负项分开算，只有"正 > 负"才相减，负的一律钳到 0，
//   结果再钳到 255（饱和）。这与工程里 CSC"正负分开相加"的做法一致。
//
// 【权重和都是 2 的幂】R/B 相位：4+2×4−4 = 8 → >>3；G 相位：2+2×2−2 = 4 → >>2
//   —— 全部只有加法和移位，仍然 0 乘法器。
//
// 流水：组合算 + 1 级寄存输出（LAT=1），与 valid 同拍 —— 接口与双线性核完全一致，
//      顶层可以"换核不改线"。
//========================================================================
`timescale 1ns/1ps

module demosaic_mhc (
    input               clk,
    input               rst_n,
    input  [199:0]      win_flat,     // 5×5 窗口（25×8bit 打包）
    input  [1:0]        phase,        // 中心相位：00=R 01=Gr 10=Gb 11=B
    input               valid_in,
    output reg  [7:0]   r_out,
    output reg  [7:0]   g_out,
    output reg  [7:0]   b_out,
    output              valid_out
);

    localparam PH_R  = 2'b00;
    localparam PH_GR = 2'b01;
    localparam PH_GB = 2'b10;
    localparam PH_B  = 2'b11;

    //========================================================================
    // 拆窗口：W<行><列>，行0 最上、列0 最左、W22 中心
    // （打包顺序由 line_buffer_nxn 决定：win_flat[(行*5+列)*8 +: 8]）
    //========================================================================
    wire [7:0] W00 = win_flat[0*8  +: 8];
    wire [7:0] W01 = win_flat[1*8  +: 8];
    wire [7:0] W02 = win_flat[2*8  +: 8];   // 上远端
    wire [7:0] W03 = win_flat[3*8  +: 8];
    wire [7:0] W04 = win_flat[4*8  +: 8];
    wire [7:0] W10 = win_flat[5*8  +: 8];
    wire [7:0] W11 = win_flat[6*8  +: 8];
    wire [7:0] W12 = win_flat[7*8  +: 8];   // 上
    wire [7:0] W13 = win_flat[8*8  +: 8];
    wire [7:0] W14 = win_flat[9*8  +: 8];
    wire [7:0] W20 = win_flat[10*8 +: 8];   // 左远端
    wire [7:0] W21 = win_flat[11*8 +: 8];   // 左
    wire [7:0] W22 = win_flat[12*8 +: 8];   // 中心
    wire [7:0] W23 = win_flat[13*8 +: 8];   // 右
    wire [7:0] W24 = win_flat[14*8 +: 8];   // 右远端
    wire [7:0] W30 = win_flat[15*8 +: 8];
    wire [7:0] W31 = win_flat[16*8 +: 8];
    wire [7:0] W32 = win_flat[17*8 +: 8];   // 下
    wire [7:0] W33 = win_flat[18*8 +: 8];
    wire [7:0] W34 = win_flat[19*8 +: 8];
    wire [7:0] W40 = win_flat[20*8 +: 8];
    wire [7:0] W41 = win_flat[21*8 +: 8];
    wire [7:0] W42 = win_flat[22*8 +: 8];   // 下远端
    wire [7:0] W43 = win_flat[23*8 +: 8];
    wire [7:0] W44 = win_flat[24*8 +: 8];

    //========================================================================
    // 公用小组和（组合，只算一次）
    //========================================================================
    wire [9:0] cross4    = {2'b00, W12} + {2'b00, W32} + {2'b00, W21} + {2'b00, W23}; // 十字 4 个（最大 1020）
    wire [9:0] diag4     = {2'b00, W11} + {2'b00, W13} + {2'b00, W31} + {2'b00, W33}; // 对角 4 个
    wire [9:0] side2_far = {2'b00, W20} + {2'b00, W24};                               // 左右远端（最大 510）
    wire [9:0] updn2_far = {2'b00, W02} + {2'b00, W42};                               // 上下远端
    wire [9:0] side2     = {2'b00, W21} + {2'b00, W23};                               // 左右
    wire [9:0] updn2     = {2'b00, W12} + {2'b00, W32};                               // 上下
    wire [10:0] far4     = {1'b0, side2_far} + {1'b0, updn2_far};                     // 远端十字 4 个

    //========================================================================
    // MHC 小函数：out = sat8( (pos_a + pos_b − neg) >> sh )，负数钳 0、超 255 钳 255
    //   输入都按 13bit 传（最大 4×255 + 2×1020 = 3060，13bit 够）
    //========================================================================
    function [7:0] mhc8;
        input [12:0] pos_a;    // 中心项（×4 或 ×2 放大）
        input [12:0] pos_b;    // 邻居项（×2 放大）
        input [12:0] neg;      // 远端项（要减掉的）
        input [3:0]  sh;       // 右移位数（R/B 相位=3，G 相位=2）
        reg   [12:0] diff;
        begin
            diff = pos_a + pos_b;
            if (diff > neg) begin
                diff = (diff - neg) >> sh;
                mhc8 = (diff > 13'd255) ? 8'd255 : diff[7:0];
            end else begin
                mhc8 = 8'd0;   // 负数（暗处细节项过大）→ 钳到 0
            end
        end
    endfunction

    //========================================================================
    // 按相位选公式（组合逻辑；结果打 1 级寄存器）
    //========================================================================
    reg [7:0] r_c, g_c, b_c;
    always @(*) begin
        case (phase)
            PH_R: begin
                r_c = W22;                                            // 直通
                g_c = mhc8({W22, 2'b00}, {1'b0, cross4, 1'b0}, far4, 4'd3);
                b_c = mhc8({W22, 2'b00}, {1'b0, diag4,  1'b0}, far4, 4'd3);
            end
            PH_B: begin
                b_c = W22;
                g_c = mhc8({W22, 2'b00}, {1'b0, cross4, 1'b0}, far4, 4'd3);
                r_c = mhc8({W22, 2'b00}, {1'b0, diag4,  1'b0}, far4, 4'd3);
            end
            PH_GR: begin
                g_c = W22;
                r_c = mhc8({W22, 1'b0}, {1'b0, side2, 1'b0}, {3'b000, side2_far}, 4'd2);
                b_c = mhc8({W22, 1'b0}, {1'b0, updn2, 1'b0}, {3'b000, updn2_far}, 4'd2);
            end
            default: begin                                            // PH_GB
                g_c = W22;
                b_c = mhc8({W22, 1'b0}, {1'b0, side2, 1'b0}, {3'b000, side2_far}, 4'd2);
                r_c = mhc8({W22, 1'b0}, {1'b0, updn2, 1'b0}, {3'b000, updn2_far}, 4'd2);
            end
        endcase
    end

    //========================================================================
    // 输出寄存 + valid 打 1 拍（LAT=1）
    //========================================================================
    reg valid_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            r_out   <= 8'd0;
            g_out   <= 8'd0;
            b_out   <= 8'd0;
            valid_r <= 1'b0;
        end else begin
            r_out   <= r_c;
            g_out   <= g_c;
            b_out   <= b_c;
            valid_r <= valid_in;
        end
    end

    assign valid_out = valid_r;

endmodule